// Writes dist/THIRD_PARTY_LICENSES.txt: the licence text of every npm package whose code is bundled
// into the extension or its webview. The list comes from the bundler itself (esbuild's metafile),
// so it cannot drift from what actually ships. Run after a build: `npm run licenses`.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

async function inputsOf(options) {
  const result = await esbuild.build({
    absWorkingDir: root,
    bundle: true,
    write: false,
    metafile: true,
    logLevel: 'silent',
    outdir: join(root, 'dist', '.licenses-scan'),
    ...options,
  });
  return Object.keys(result.metafile.inputs);
}

const inputs = [
  ...(await inputsOf({
    entryPoints: ['src/vscode/extension.ts'],
    format: 'cjs',
    platform: 'node',
    external: ['vscode'],
  })),
  ...(await inputsOf({
    entryPoints: ['src/webview/app/main.tsx'],
    format: 'esm',
    platform: 'browser',
    splitting: true,
    jsx: 'automatic',
    loader: { '.ttf': 'file', '.css': 'css' },
    alias: { 'elkjs/lib/elk.bundled.js': './scripts/stubs/elk.mjs' },
  })),
];

// The package directory is everything up to and including the LAST node_modules/<name> segment,
// so nested copies (a dependency's own node_modules) are found where they really are.
const packageDirs = new Set();
for (const input of inputs) {
  const match = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input.replace(/\\/g, '/'));
  if (match) packageDirs.add(match[1]);
}

const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.|-|$)/i;
const entries = [];
const missing = [];
for (const dir of [...packageDirs].sort()) {
  const absolute = join(root, dir);
  const manifestPath = join(absolute, 'package.json');
  if (!existsSync(manifestPath)) continue;
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const license =
    typeof manifest.license === 'string'
      ? manifest.license
      : Array.isArray(manifest.licenses)
        ? manifest.licenses.map((l) => l.type).join(' OR ')
        : 'not stated in package.json';
  const files = readdirSync(absolute).filter((name) => LICENSE_FILE.test(name));
  const texts = files.map((name) => readFileSync(join(absolute, name), 'utf8').trim());
  if (texts.length === 0) missing.push(`${manifest.name}@${manifest.version}`);
  entries.push({ name: manifest.name, version: manifest.version, license, texts });
}

// The same package version may be installed in several places; list it once.
const unique = new Map();
for (const entry of entries) unique.set(`${entry.name}@${entry.version}`, entry);

const rule = '='.repeat(78);
const lines = [
  'Third-party software bundled with AgentCanopy',
  '',
  'This file lists every npm package whose code is included in the extension bundle or',
  'its webview, with the licence text each package ships. It is generated by',
  'scripts/third-party-licenses.mjs from the bundler output.',
  '',
];
for (const [id, entry] of [...unique.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  lines.push(rule, `${id}`, `License: ${entry.license}`, rule, '');
  if (entry.texts.length === 0) {
    lines.push('(This package ships no licence file. See its package.json and repository.)', '');
  } else {
    for (const text of entry.texts) lines.push(text, '');
  }
}

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist', 'THIRD_PARTY_LICENSES.txt'), `${lines.join('\n')}\n`);
console.log(`dist/THIRD_PARTY_LICENSES.txt: ${unique.size} packages`);
if (missing.length > 0) console.log(`without a licence file: ${missing.join(', ')}`);
